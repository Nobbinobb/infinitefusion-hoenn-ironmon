namespace Ironmon.Tracker.App.Components.Common;

/// <summary>
/// Defines stable Pokemon value identifiers received from the game.
/// </summary>
internal static class PokemonValueIds
{
    /// <summary>
    /// Gets the male gender identifier.
    /// </summary>
    internal const string Male = "MALE";

    /// <summary>
    /// Gets the female gender identifier.
    /// </summary>
    internal const string Female = "FEMALE";

    /// <summary>
    /// Gets the male gender symbol.
    /// </summary>
    internal const string MaleSymbol = "\u2642";

    /// <summary>
    /// Gets the female gender symbol.
    /// </summary>
    internal const string FemaleSymbol = "\u2640";

    /// <summary>
    /// Gets the male gender CSS class.
    /// </summary>
    internal const string MaleCssClass = "male";

    /// <summary>
    /// Gets the female gender CSS class.
    /// </summary>
    internal const string FemaleCssClass = "female";

}
