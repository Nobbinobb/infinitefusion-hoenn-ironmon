    /// <summary>
    /// Registers semantic discovery of native intrinsics and compiler-supplied scripts.
    /// </summary>
    /// <param name="context">The incremental generator registration context.</param>
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var intrinsics = context.SyntaxProvider.ForAttributeWithMetadataName(_maintenanceAttribute, static (node, _) => node is MethodDeclarationSyntax, static (attribute, _) => (IMethodSymbol)attribute.TargetSymbol);
        context.RegisterSourceOutput(intrinsics, static (output, method) => Generate(output, method, default, false));
        var scripts = context.SyntaxProvider.ForAttributeWithMetadataName(_scriptAttribute, static (node, _) => node is MethodDeclarationSyntax, static (attribute, _) => (IMethodSymbol)attribute.TargetSymbol);
        context.RegisterSourceOutput(scripts.Combine(context.AdditionalTextsProvider.Collect()), static (output, input) => Generate(output, input.Left, input.Right, true));
    }

    /// <summary>
    /// Emits one independently named strongly typed partial implementation or a build error.
    /// </summary>
    /// <param name="context">Receives generated source and diagnostics.</param>
    /// <param name="method">The explicitly attributed partial declaration.</param>
    /// <param name="files">The compiler-supplied dedicated SQL scripts.</param>
    /// <param name="script">Whether the declaration refers to a dedicated script.</param>
    private static void Generate(SourceProductionContext context, IMethodSymbol method, ImmutableArray<AdditionalText> files, bool script)
    {
        try
        {
            Validate(method);
            AttributeData attribute = method.GetAttributes().Single(value => value.AttributeClass?.ToDisplayString() == (script ? _scriptAttribute : _maintenanceAttribute));
            string body;
            if (script)
            {
                if (!method.ReturnsVoid || method.Parameters.Length != 2)
                    throw new InvalidOperationException("A dedicated script must return void and take only connection and transaction.");

                string path = ((string?)attribute.ConstructorArguments[0].Value ?? string.Empty).Replace('\\', '/');
                if (path.Length == 0 || path.StartsWith(_pathSeparator, StringComparison.Ordinal) || path.Split('/').Any(part => part is _parentPathComponent or _currentPathComponent))
                    throw new InvalidOperationException("A dedicated script needs an unambiguous project-relative AdditionalFile path.");

                AdditionalText file = files.SingleOrDefault(value => value.Path.Replace('\\', '/').EndsWith(_pathSeparator + path, StringComparison.OrdinalIgnoreCase)) ?? throw new InvalidOperationException("The dedicated SQL script is missing from compiler AdditionalFiles.");
                string text = file.GetText(context.CancellationToken)?.ToString() ?? throw new InvalidOperationException("The dedicated SQL script could not be read.");
                if (string.IsNullOrWhiteSpace(text))
                    throw new InvalidOperationException("A dedicated SQL script cannot be empty.");

                body = Command(Literal(text), _voidExecution);
            }
            else
            {
                int operation = Convert.ToInt32(attribute.ConstructorArguments[0].Value, System.Globalization.CultureInfo.InvariantCulture);
                ValidateIntrinsicSignature(operation, method);
                body = Intrinsic(operation, method);
            }

            for (int index = 2; index < method.Parameters.Length; index++)
                body = body.Replace(_argumentTokenPrefix + index.ToString(System.Globalization.CultureInfo.InvariantCulture) + _argumentTokenSuffix, _at + method.Parameters[index].Name);

            INamedTypeSymbol container = method.ContainingType;
            string accessibility = container.DeclaredAccessibility == Accessibility.Public ? _publicDeclaration : _internalDeclaration;
            string methodAccessibility = method.DeclaredAccessibility == Accessibility.Public ? _publicAccess : _internalAccess;
            string parameters = string.Join(_comma, method.Parameters.Select(parameter => parameter.Type.ToDisplayString(_typeDisplay) + _space + _at + parameter.Name));
            StringBuilder output = new(_header);
            output.Append(_namespace).Append(container.ContainingNamespace.ToDisplayString()).Append(';').AppendLine();
            output.Append(accessibility).Append(_class).Append(container.Name).Append(_openBody);
            string documentation = method.GetDocumentationCommentXml() ?? string.Empty;
            if (documentation.Length > 0)
            {
                int start = documentation.IndexOf('>') + 1;
                int end = documentation.LastIndexOf(_documentationEnd, StringComparison.Ordinal);
                if (end > start)
                {
                    foreach (string line in documentation.Substring(start, end - start).Trim().Split('\n'))
                        output.Append(_indent).Append(_documentationPrefix).AppendLine(line.Trim());
                }
            }

            output.Append(_indent).Append(methodAccessibility).Append(_partial).Append(method.ReturnType.ToDisplayString(_typeDisplay)).Append(_space).Append(_at).Append(method.Name).Append('(').Append(parameters).Append(')').Append(_openBody);
            foreach (string line in body.Split('\n'))
                output.Append(_indent).Append(_indent).AppendLine(line);

            output.Append(_indent).Append(_closeBody).Append(_closeBody);
            context.AddSource(container.ToDisplayString().Replace('.', '_') + _currentPathComponent + method.Name + _suffix, SourceText.From(output.ToString(), Encoding.UTF8));
        }
        catch (Exception error) when (error is InvalidOperationException or ArgumentException)
        {
            context.ReportDiagnostic(Diagnostic.Create(_unsupported, method.Locations.First(), error.Message));
        }
    }

    /// <summary>
    /// Checks the explicit partial declaration and external connection ownership boundary.
    /// </summary>
    /// <param name="method">The declaration to validate.</param>
    private static void Validate(IMethodSymbol method)
    {
        INamedTypeSymbol container = method.ContainingType;
        if (!container.IsStatic || container.ContainingType is not null || container.ContainingNamespace.IsGlobalNamespace || container.TypeParameters.Length != 0 || !method.IsStatic || method.TypeParameters.Length != 0 || !method.IsPartialDefinition || method.DeclaredAccessibility is not (Accessibility.Internal or Accessibility.Public) || method.Parameters.Any(parameter => parameter.RefKind != RefKind.None))
            throw new InvalidOperationException("Maintenance declarations must be nongeneric static partial methods on a top-level static partial class.");

        if (method.Parameters.Length < 2 || method.Parameters[0].Name != _connectionName || method.Parameters[1].Name != _transactionName || method.Parameters[0].Type.ToDisplayString() != _connectionType || method.Parameters[1].Type.ToDisplayString().TrimEnd('?') != _transactionType)
            throw new InvalidOperationException("Maintenance methods must begin with the caller-owned connection and nullable transaction parameters.");
    }

    /// <summary>
    /// Rejects mismatched typed native contracts before generating any provider implementation.
    /// </summary>
    /// <param name="operation">The explicitly selected intrinsic code.</param>
    /// <param name="method">The author-maintained typed partial declaration.</param>
    private static void ValidateIntrinsicSignature(int operation, IMethodSymbol method)
    {
        if (operation < 0 || operation > 30)
            throw new InvalidOperationException("Unknown native SQLite maintenance operation.");

        string expectedReturn = operation switch
        {
            0 or 8 => _stringType,
            1 or 2 or 3 or 4 or 9 or 10 or 28 => _longType,
            15 => _booleanType,
            16 => _schemaObjectsType,
            17 => _namesType,
            18 => _referencesType,
            19 => _columnsType,
            20 => _rowsType,
            30 => _streamRowsType,
            _ => _voidType
        };
        if (method.ReturnType.ToDisplayString(_typeDisplay) != expectedReturn)
            throw new InvalidOperationException("The native maintenance declaration has an incompatible return type.");

        string[] extraTypes = operation switch
        {
            4 or 18 or 19 or 20 or 21 or 22 or 25 or 29 or 30 => [_stringType],
            15 or 23 => [_stringType, _stringType],
            24 => [_schemaObjectType],
            26 => [_stringType, _stringType, _stringType],
            27 => [_stringType, _columnsType, _objectArrayType],
            28 => [_stringType, _stringType, _longType],
            _ => []
        };
        if (method.Parameters.Length != extraTypes.Length + 2 || method.Parameters.Skip(2).Select(parameter => parameter.Type.ToDisplayString(_typeDisplay)).Where((type, index) => type != extraTypes[index]).Any())
            throw new InvalidOperationException("The native maintenance declaration has incompatible parameter types.");

        string[] localNames = operation switch { 16 or 17 or 18 or 19 or 20 => [_commandLocal, _readerLocal, _resultLocal], 27 => [_commandLocal, _quotedColumnsLocal, _parameterNamesLocal, _columnLocal, _parameterLocal], 29 => [_commandLocal, _readerLocal], _ => [_commandLocal] };
        if (method.Parameters.Skip(2).Any(parameter => localNames.Contains(parameter.Name, StringComparer.Ordinal)))
            throw new InvalidOperationException("A maintenance parameter name conflicts with a generated provider local.");
    }

    /// <summary>
    /// Compiles one bounded native metadata or schema-maintenance operation.
    /// </summary>
    /// <param name="operation">The explicitly selected operation code.</param>
    /// <param name="method">The typed declaration whose argument count is validated.</param>
    /// <returns>The direct provider method body.</returns>
    private static string Intrinsic(int operation, IMethodSymbol method)
    {
        int extra = operation switch { 4 or 18 or 19 or 20 or 21 or 22 or 24 or 25 or 29 or 30 => 1, 15 or 23 => 2, 26 or 27 or 28 => 3, _ => 0 };
        if (method.Parameters.Length != extra + 2)
            throw new InvalidOperationException("The native maintenance declaration has the wrong argument count.");

        return operation switch
        {
            0 => Fixed(_sqliteVersionSql, _stringExecution),
            1 => Fixed(_pageSizeSql, _longExecution),
            2 => Fixed(_pageCountSql, _longExecution),
            3 => Fixed(_freeCountSql, _longExecution),
            4 => Command(_countTableExpression + Quote(_argumentTwo), _longExecution),
            5 => Fixed(_configureDurabilitySql, _voidExecution),
            6 => Fixed(_compactPageSizeSql, _voidExecution),
            7 => Fixed(_checkpointSql, _voidExecution),
            8 => Fixed(_journalModeSql, _stringExecution),
            9 => Fixed(_synchronousSql, _longExecution),
            10 => Fixed(_foreignKeysSql, _longExecution),
            11 => Fixed(_beginMigrationSql, _voidExecution),
            12 => Fixed(_restoreMigrationSql, _voidExecution),
            13 => Fixed(_vacuumSql, _voidExecution),
            14 => Fixed(_rollbackJournalSql, _voidExecution),
            15 => Fixed(_hasColumnSql, Bind(_tableParameter, _argumentTwo) + Bind(_columnParameter, _argumentThree) + _booleanExecution),
            16 => Fixed(_migrationObjectsSql, _readObjects),
            17 => Fixed(_tableNamesSql, _readNames),
            18 => Fixed(_foreignReferencesSql, Bind(_tableParameter, _argumentTwo) + _readReferences),
            19 => Command(_tableColumnsExpression + Quote(_argumentTwo) + _closePragmaExpression, _readColumns),
            20 => Command(_tableRowsExpression + Quote(_argumentTwo), _readRows),
            21 => Command(_dropTriggerExpression + Quote(_argumentTwo), _voidExecution),
            22 => Command(_dropTableExpression + Quote(_argumentTwo), _voidExecution),
            23 => Command(_alterTableExpression + Quote(_argumentTwo) + _renameTableExpression + Quote(_argumentThree), _voidExecution),
            24 => Command(_schemaObjectExpression, _voidExecution),
            25 => Command(_argumentTwo, _voidExecution),
            26 => Command(_replacementDefinitionExpression, _voidExecution),
            27 => Command(_emptyStringExpression, _insertRows),
            28 => Command(_referenceCountExpression + Quote(_argumentTwo) + _whereExpression + Quote(_argumentThree) + _referenceValueExpression, Bind(_valueParameter, _argumentFour) + _longExecution),
            29 => Fixed(_foreignKeyAuditSql, _integrityCheck),
            30 => Command(_tableRowsExpression + Quote(_argumentTwo), _streamRows),
            _ => throw new InvalidOperationException("Unknown native SQLite maintenance operation.")
        };
    }

    /// <summary>
    /// Emits one exact constant command with no runtime lookup step.
    /// </summary>
    /// <param name="sql">The provider intrinsic compiled into generated code.</param>
    /// <param name="execution">The type-specific execution and materialization body.</param>
    /// <returns>The complete provider body.</returns>
    private static string Fixed(string sql, string execution)
        => Command(Literal(sql), execution);

    /// <summary>
    /// Emits caller-owned command and transaction binding around a generated expression.
    /// </summary>
    /// <param name="expression">The generated command-text expression.</param>
    /// <param name="execution">The execution body with any generated parameter bindings.</param>
    /// <returns>The complete provider body.</returns>
    private static string Command(string expression, string execution)
        => _commandStart + expression + _statementEnd + execution;

    /// <summary>
    /// Emits a native inferred parameter preserving SQLite value storage classes.
    /// </summary>
    /// <param name="name">The generated parameter name.</param>
    /// <param name="value">The authored typed method parameter expression.</param>
    /// <returns>The provider parameter binding line.</returns>
    private static string Bind(string name, string value)
        => _addParameterExpression + Literal(name) + _argumentSeparator + value + _invocationEnd;

    /// <summary>
    /// Emits safe runtime quoting for one whole metadata-owned identifier.
    /// </summary>
    /// <param name="value">The generated parameter expression.</param>
    /// <returns>The identifier-quoting expression.</returns>
    private static string Quote(string value)
        => _quoteIdentifierExpression + value + _closeInvocation;

    /// <summary>
    /// Quotes a generated C# literal, including script newlines and escape characters.
    /// </summary>
    /// <param name="value">The exact generated literal value.</param>
    /// <returns>A valid escaped C# string literal.</returns>
    private static string Literal(string value)
        => Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(value, true);
}
