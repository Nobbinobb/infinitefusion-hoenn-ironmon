using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;
using System;
using System.Globalization;
using System.Linq;
using System.Text;

namespace Ironmon.Sqlite.QueryGenerator;

/// <summary>
/// Emits optional reusable command factories from the same validated typed non-query definitions.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class SqlCommandFactoryGenerator : IIncrementalGenerator
{
    private const string _attribute = "Ironmon.Sqlite.Querying.SqlCommandFactoryAttribute";
    private const string _definitions = "Definitions";
    private const string _id = "ISQL003";
    private const string _category = "QueryGeneration";
    private const string _messageFormat = "{0}";
    private const string _sourceSuffix = ".CommandFactory.g.cs";
    private const string _internal = "internal";
    private const string _public = "public";
    private const string _separator = ", ";
    private const string _argumentPrefix = "global::Microsoft.Data.Sqlite.SqliteConnection connection, global::Microsoft.Data.Sqlite.SqliteTransaction? transaction";
    private const string _parameterPrefix = "@p";
    private const string _header = "// <auto-generated/>\n#nullable enable\nnamespace {0};\n\n{1} static partial class @{2}\n{{\n";
    private const string _documentation = "    /// <summary>\n    /// Creates the caller-owned reusable command for this generated operation.\n    /// </summary>\n    /// <param name=\"connection\">The existing open SQLite connection.</param>\n    /// <param name=\"transaction\">The caller-owned transaction, or null outside one.</param>\n";
    private const string _parameterDocumentation = "    /// <param name=\"{0}\">The exact typed value bound to the reusable command.</param>\n";
    private const string _returnDocumentation = "    /// <returns>The bound command; the caller owns execution, parameter replacement and disposal.</returns>\n";
    private const string _method = "    internal static global::Microsoft.Data.Sqlite.SqliteCommand @Create{0}Command({1})\n    {{\n        global::System.ArgumentNullException.ThrowIfNull(connection);\n        var command = connection.CreateCommand();\n        try\n        {{\n            command.Transaction = transaction;\n            command.CommandText = {2};\n";
    private const string _typedParameter = "            command.Parameters.Add({0}, global::Microsoft.Data.Sqlite.SqliteType.{1}).Value = (object?)({2}) ?? global::System.DBNull.Value;\n";
    private const string _inferredParameter = "            command.Parameters.AddWithValue({0}, (object?)({1}) ?? global::System.DBNull.Value);\n";
    private const string _footer = "            return command;\n        }\n        catch\n        {\n            command.Dispose();\n            throw;\n        }\n    }\n}\n";
    private static readonly DiagnosticDescriptor _unsupported = new(_id, "Invalid reusable SQLite command definition", _messageFormat, _category, DiagnosticSeverity.Error, true);

    /// <summary>
    /// Registers explicitly requested factories without changing ordinary generated methods.
    /// </summary>
    /// <param name="context">The compiler's incremental source-generation context.</param>
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var targets = context.SyntaxProvider.ForAttributeWithMetadataName(_attribute, static (node, _) => node is MethodDeclarationSyntax, static (attribute, _) => (IMethodSymbol)attribute.TargetSymbol);
        context.RegisterSourceOutput(targets.Combine(context.CompilationProvider), static (output, input) => Generate(output, input.Left, input.Right));
    }

    /// <summary>
    /// Emits one optional factory using the original query's SQL and typed bindings.
    /// </summary>
    /// <param name="context">Receives generated source or a build diagnostic.</param>
    /// <param name="method">The explicitly marked nested definition method.</param>
    /// <param name="compilation">The current semantic compilation.</param>
    private static void Generate(SourceProductionContext context, IMethodSymbol method, Compilation compilation)
    {
        try
        {
            INamedTypeSymbol target = method.ContainingType.ContainingType ?? throw new InvalidOperationException("Reusable command definitions require a nested Definitions class.");
            if (method.ContainingType.Name != _definitions || !target.IsStatic || target.TypeParameters.Length != 0 || target.ContainingType is not null)
                throw new InvalidOperationException("Reusable command definitions require a top-level static query container and its nested Definitions class.");

            QueryPlan plan = SqliteQueryCompiler.Compile(method, compilation, context.CancellationToken);
            if (plan.Mode != QueryMode.NonQuery)
                throw new InvalidOperationException("Reusable command factories support only non-query definitions.");

            StringBuilder output = new();
            output.AppendFormat(CultureInfo.InvariantCulture, _header, target.ContainingNamespace.ToDisplayString(), target.DeclaredAccessibility == Accessibility.Public ? _public : _internal, target.Name);
            output.Append(_documentation);
            foreach (IParameterSymbol parameter in method.Parameters)
                output.AppendFormat(CultureInfo.InvariantCulture, _parameterDocumentation, parameter.Name);

            output.Append(_returnDocumentation);
            string arguments = _argumentPrefix + string.Concat(method.Parameters.Select(parameter => _separator + SqliteQueryCompiler.TypeName(parameter.Type) + ' ' + '@' + parameter.Name));
            output.AppendFormat(CultureInfo.InvariantCulture, _method, method.Name, arguments, Literal(plan.Sql));
            for (int index = 0; index < plan.Parameters.Count; index++)
            {
                var (expression, storage) = plan.Parameters[index];
                string parameter = Literal(_parameterPrefix + index.ToString(CultureInfo.InvariantCulture));
                if (storage is null)
                {
                    output.AppendFormat(CultureInfo.InvariantCulture, _inferredParameter, parameter, expression);
                }
                else
                {
                    output.AppendFormat(CultureInfo.InvariantCulture, _typedParameter, parameter, storage, expression);
                }
            }

            output.Append(_footer);
            context.AddSource(target.ToDisplayString().Replace('.', '_') + '_' + method.Name + _sourceSuffix, SourceText.From(output.ToString(), Encoding.UTF8));
        }
        catch (InvalidOperationException error)
        {
            context.ReportDiagnostic(Diagnostic.Create(_unsupported, method.Locations.First(), error.Message));
        }
    }

    /// <summary>
    /// Quotes SQL and parameter names as exact compiler-generated C# literals.
    /// </summary>
    /// <param name="value">The exact text to embed in generated code.</param>
    /// <returns>The escaped C# string literal.</returns>
    private static string Literal(string value)
        => Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(value, true);
}
