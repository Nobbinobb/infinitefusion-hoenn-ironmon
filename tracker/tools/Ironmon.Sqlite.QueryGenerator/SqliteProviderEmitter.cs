using Microsoft.CodeAnalysis;
using System.Globalization;
using System.Linq;
using System.Security;
using System.Text;
using System.Xml.Linq;

namespace Ironmon.Sqlite.QueryGenerator;

/// <summary>
/// Emits direct synchronous provider methods with generated SQL, typed bindings and ordinal readers.
/// </summary>
internal static class SqliteProviderEmitter
{
    private const string _header = "// <auto-generated/>\n#nullable enable\n";
    private const string _namespace = "namespace ";
    private const string _class = "static partial class ";
    private const string _public = "public ";
    private const string _internal = "internal ";
    private const string _method = "    internal static ";
    private const string _connectionArgument = "global::Microsoft.Data.Sqlite.SqliteConnection connection, global::Microsoft.Data.Sqlite.SqliteTransaction? transaction";
    private const string _separator = ", ";
    private const string _guard = "        global::System.ArgumentNullException.ThrowIfNull(connection);";
    private const string _command = "        global::Microsoft.Data.Sqlite.SqliteCommand command = lease.Command;";
    private const string _transaction = "        command.Transaction = transaction;";
    private const string _commandText = "                factoryCommand.CommandText = ";
    private const string _parameterPrefix = "@p";
    private const string _typedParameterStart = "                factoryCommand.Parameters.Add(";
    private const string _typedParameterMiddle = ", global::Microsoft.Data.Sqlite.SqliteType.";
    private const string _inferredParameterStart = "                factoryCommand.Parameters.AddWithValue(";
    private const string _reader = "        using global::Microsoft.Data.Sqlite.SqliteDataReader reader = lease.ExecuteReader();";
    private const string _readFirst = "        if (!lease.Read(reader))\n            return null;\n";
    private const string _readRows = "        while (lease.Read(reader))\n        {";
    private const string _yield = "            yield return new ";
    private const string _returnRow = "        return new ";
    private const string _returnNonQuery = "        return lease.ExecuteNonQuery();";
    private const string _returnIdentity = "        return (long)(lease.ExecuteScalar() ?? throw new global::System.IO.InvalidDataException(\"SQLite did not return an inserted row identity.\"));";
    private const string _returnResolvedIdentity = "        return (long)(lease.ExecuteScalar() ?? throw new global::System.IO.InvalidDataException(\"SQLite did not resolve a row identity for the declared conflict key.\"));";
    private const string _returnScalarInt64 = "        return (long)(lease.ExecuteScalar() ?? throw new global::System.IO.InvalidDataException(\"SQLite did not return the required Int64 aggregate.\"));";
    private const string _docPrefix = "    /// ";
    private const string _summaryTag = "summary";
    private const string _parameterTag = "param";
    private const string _returnsTag = "returns";
    private const string _nameAttribute = "name";
    private const string _parameterDocStart = "<param name=\"";
    private const string _parameterDocMiddle = "\">";
    private const string _parameterDocEnd = "</param>";
    private const string _connectionDoc = "The already-open collection connection used by this operation.";
    private const string _transactionDoc = "The owning transaction, or null outside a transaction; this method never commits it.";
    private const string _summaryFallback = "Executes the build-time generated SQLite operation.";
    private const string _parameterFallback = "The exact typed value bound to the generated SQLite statement.";
    private const string _returnsFallback = "The typed result of the generated SQLite operation.";
    private const string _connectionName = "connection";
    private const string _transactionName = "transaction";
    private const string _methodIndent = "    ";
    private const string _rowIndent = "        ";
    private const string _yieldIndent = "            ";
    private const string _summaryOpen = "<summary>";
    private const string _summaryClose = "</summary>";
    private const string _returnsOpen = "<returns>";
    private const string _returnsClose = "</returns>";
    private const string _assignment = " = ";
    private const string _lineBreak = "\n";
    private const string _windowsLineBreak = "\r\n";
    private const string _identityPrefix = "_generatedQueryIdentity";
    private const string _identityField = "    private static readonly object ";
    private const string _identityInitializer = " = new();";
    private const string _rentStart = "        using global::Ironmon.Sqlite.Execution.SqliteCommandLease lease = global::Ironmon.Sqlite.Execution.SqliteCommandCache.Rent(connection, ";
    private const string _rentFactory = ", static factoryConnection =>\n        {\n            var factoryCommand = factoryConnection.CreateCommand();\n            try\n            {";
    private const string _rentEnd = "                return factoryCommand;\n            }\n            catch\n            {\n                factoryCommand.Dispose();\n                throw;\n            }\n        });";
    private const string _inferredSlotEnd = ", global::System.DBNull.Value);";
    private const string _typedSlotEnd = ");";
    private const string _bindingStart = "        command.Parameters[";
    private const string _bindingValue = "].Value = (object?)(";
    private const string _bindingEnd = ") ?? global::System.DBNull.Value;";

    /// <summary>
    /// Generates one complete consumer partial class without a runtime query registry or translator.
    /// </summary>
    /// <param name="target">The attributed outer query class.</param>
    /// <param name="plans">The validated operations to emit.</param>
    /// <returns>The compiler-generated C# implementation.</returns>
    internal static string Emit(INamedTypeSymbol target, QueryPlan[] plans)
    {
        StringBuilder output = new(_header);
        output.Append(_namespace).Append(target.ContainingNamespace.ToDisplayString()).Append(';').AppendLine();
        output.AppendLine();
        output.Append(target.DeclaredAccessibility == Accessibility.Public ? _public : _internal).Append(_class).Append('@').AppendLine(target.Name);
        output.Append('{').AppendLine();
        for (int index = 0; index < plans.Length; index++)
            output.Append(_identityField).Append(_identityPrefix).Append(index.ToString(CultureInfo.InvariantCulture)).AppendLine(_identityInitializer);

        output.AppendLine();
        int identity = 0;
        foreach (QueryPlan plan in plans)
        {
            Documentation(output, plan.Method);
            output.Append(_method).Append(SqliteQueryCompiler.TypeName(plan.Result)).Append(' ').Append('@').Append(plan.Method.Name).Append('(').Append(_connectionArgument);
            foreach (IParameterSymbol parameter in plan.Method.Parameters)
                output.Append(_separator).Append(SqliteQueryCompiler.TypeName(parameter.Type)).Append(' ').Append('@').Append(parameter.Name);

            output.Append(')').AppendLine();
            output.Append(_methodIndent).Append('{').AppendLine();
            output.AppendLine(_guard);
            CommandLease(output, plan, identity++);
            output.AppendLine(_command).AppendLine(_transaction);
            for (int index = 0; index < plan.Parameters.Count; index++)
            {
                output.Append(_bindingStart).Append(index.ToString(CultureInfo.InvariantCulture)).Append(_bindingValue).Append(plan.Parameters[index].Expression).AppendLine(_bindingEnd);
            }

            output.AppendLine();
            if (plan.Mode is QueryMode.FirstOrDefault or QueryMode.Enumerable)
            {
                output.AppendLine(_reader);
                output.AppendLine(plan.Mode == QueryMode.FirstOrDefault ? _readFirst : _readRows);
                string indent = plan.Mode == QueryMode.Enumerable ? _yieldIndent : _rowIndent;
                output.Append(plan.Mode == QueryMode.Enumerable ? _yield : _returnRow).AppendLine(plan.RowType);
                output.Append(indent).Append('{').AppendLine();
                foreach (var (Property, Reader) in plan.Projection)
                    output.Append(indent).Append(_methodIndent).Append('@').Append(Property).Append(_assignment).Append(Reader).Append(',').AppendLine();

                output.Append(indent).Append('}').Append(';').AppendLine();
                if (plan.Mode == QueryMode.Enumerable)
                    output.Append(_rowIndent).Append('}').AppendLine();
            }
            else
            {
                output.AppendLine(plan.Mode switch
                {
                    QueryMode.LastInsertId => _returnIdentity,
                    QueryMode.ResolvedId => _returnResolvedIdentity,
                    QueryMode.ScalarInt64 => _returnScalarInt64,
                    _ => _returnNonQuery
                });
            }

            output.Append(_methodIndent).Append('}').AppendLine();
            output.AppendLine();
        }

        output.Append('}').AppendLine();
        return output.ToString();
    }

    /// <summary>
    /// Emits a bounded prepared-command lease and a static factory for its exact typed parameter layout.
    /// </summary>
    /// <param name="output">Receives generated connection-scoped command ownership.</param>
    /// <param name="plan">The validated native SQL and exact parameter storage types.</param>
    /// <param name="identity">The generated unique operation identity within this query class.</param>
    private static void CommandLease(StringBuilder output, QueryPlan plan, int identity)
    {
        output.Append(_rentStart).Append(_identityPrefix).Append(identity.ToString(CultureInfo.InvariantCulture)).AppendLine(_rentFactory);
        output.Append(_commandText).Append(Literal(plan.Sql)).Append(';').AppendLine();
        for (int index = 0; index < plan.Parameters.Count; index++)
        {
            string name = Literal(_parameterPrefix + index.ToString(CultureInfo.InvariantCulture));
            string? storage = plan.Parameters[index].Storage;
            if (storage is null)
                output.Append(_inferredParameterStart).Append(name).AppendLine(_inferredSlotEnd);
            else
                output.Append(_typedParameterStart).Append(name).Append(_typedParameterMiddle).Append(storage).AppendLine(_typedSlotEnd);
        }

        output.AppendLine(_rentEnd);
    }

    /// <summary>
    /// Carries the authored operation's XML contract into its generated callable method.
    /// </summary>
    /// <param name="output">Receives multiline XML documentation.</param>
    /// <param name="method">The original documented query definition.</param>
    private static void Documentation(StringBuilder output, IMethodSymbol method)
    {
        string? xml = method.GetDocumentationCommentXml();
        XElement? documentation = string.IsNullOrWhiteSpace(xml) ? null : XElement.Parse(xml);
        output.Append(_docPrefix).AppendLine(_summaryOpen);
        output.Append(_docPrefix).AppendLine(Escape(documentation?.Element(_summaryTag)?.Value.Trim() ?? _summaryFallback));
        output.Append(_docPrefix).AppendLine(_summaryClose);
        ParameterDocumentation(output, _connectionName, _connectionDoc);
        ParameterDocumentation(output, _transactionName, _transactionDoc);
        foreach (IParameterSymbol parameter in method.Parameters)
        {
            string text = documentation?.Elements(_parameterTag).SingleOrDefault(element => element.Attribute(_nameAttribute)?.Value == parameter.Name)?.Value.Trim() ?? _parameterFallback;
            ParameterDocumentation(output, parameter.Name, text);
        }

        output.Append(_docPrefix).Append(_returnsOpen).Append(Escape(documentation?.Element(_returnsTag)?.Value.Trim() ?? _returnsFallback)).AppendLine(_returnsClose);
    }

    /// <summary>
    /// Writes one exact-name parameter contract.
    /// </summary>
    /// <param name="output">Receives the generated comment.</param>
    /// <param name="name">The exact generated parameter name.</param>
    /// <param name="text">The parameter's contract.</param>
    private static void ParameterDocumentation(StringBuilder output, string name, string text)
        => output.Append(_docPrefix).Append(_parameterDocStart).Append(name).Append(_parameterDocMiddle).Append(Escape(text)).AppendLine(_parameterDocEnd);

    /// <summary>
    /// Escapes documentation text without allowing embedded markup to break generated comments.
    /// </summary>
    /// <param name="text">The original documentation text.</param>
    /// <returns>The XML-safe text with authored line breaks retained as comment lines.</returns>
    private static string Escape(string text)
        => SecurityElement.Escape(text)?.Replace(_windowsLineBreak, _lineBreak).Replace(_lineBreak, _lineBreak + _docPrefix) ?? string.Empty;

    /// <summary>
    /// Quotes generated SQL and parameter names as exact C# string literals.
    /// </summary>
    /// <param name="value">The complete value to embed in generated source.</param>
    /// <returns>A compiler-escaped C# string literal.</returns>
    private static string Literal(string value)
        => Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(value, true);
}
